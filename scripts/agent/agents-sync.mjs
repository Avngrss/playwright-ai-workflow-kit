/**
 * The agents' own copies of the kit's texts — `npm run agents:sync`. The rules, skills, commands, the MCP config
 * and the hooks are written once, in agents/; each agent reads them from its own folder in its own shape, and
 * this script writes those folders from agents/ for the agents this test home works with (agents/agents.json,
 * `npm run agents:use`; both without the file):
 *   Cursor       .cursor/rules/<name>.mdc, .cursor/commands/<name>.md, .cursor/mcp.json, .cursor/hooks.json
 *   Claude Code  .claude/rules/<name>.md (`paths:` from the rule's globs) and agents/notes/claude-code.md,
 *                .claude/commands/<name>.md, .claude/agents/reviewer.md (the /review brief as a subagent), .mcp.json,
 *                .claude/settings.json (its hooks), .claude/skills/<name>/
 *   Copilot      .github/copilot-instructions.md (agents/notes/copilot.md and the always-on rules, one file),
 *                .github/instructions/<name>.instructions.md (`applyTo` from the other rules' globs),
 *                .github/skills/<name>/ — the skills, and as skills the commands no skill is named after
 *                (/heal, /triage, /coverage) — .github/agents/reviewer.agent.md, .github/hooks/playwright-ai-kit.json
 *                (agentStop), .mcp.json (written by Claude Code's target when both are chosen)
 *   Cursor's skills are Claude's (.claude/skills/) when Claude Code is chosen — Cursor reads that folder too, a
 *                second copy would show every skill twice there — else .cursor/skills/<name>/
 * agents/hooks.json names each hook's command once: `stop` → scripts/agent/stop-check.mjs, told which agent calls it;
 * agents/permissions.json is what Claude Code may run without asking, and never.
 * A copy carries, right after its front matter, a line naming its source; `{{skill:<name>}}` in a command becomes
 * the agent's own way to load that skill. Removed: a copy whose source is gone or whose agent is no longer chosen
 * — only a file carrying that line, or a config file exactly as written here: an agent folder's own files stay.
 *
 *   npm run agents:sync               write the chosen agents' copies
 *   npm run agents:sync -- --check    list the copies that differ from agents/ and write nothing (exit 1 when any)
 *
 * qa:gate reads the same difference (scripts/gate/agents.mjs).
 */
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

const ROOT = process.cwd();
const SOURCE = "agents";
const CHOICE = "agents/agents.json";
const MARK = "Generated by npm run agents:sync from";

/** The agents the kit has copies for, by their id in agents/agents.json. */
export const AGENTS = { cursor: "Cursor", claude: "Claude Code", copilot: "GitHub Copilot" };

const read = (file) => fs.readFileSync(path.join(ROOT, file), "utf8").replace(/\r\n/g, "\n");

/** The agents this test home works with — agents/agents.json `{ "agents": ["cursor", "claude"] }`; every one without it. */
export function chosenAgents() {
  try {
    const known = JSON.parse(read(CHOICE)).agents.filter((id) => id in AGENTS);
    if (known.length) return known;
  } catch {
    // No choice written: every agent.
  }
  return Object.keys(AGENTS);
}

/** Files under a folder of the test home, from the home, with forward slashes. */
function filesUnder(dir) {
  const full = path.join(ROOT, dir);
  if (!fs.existsSync(full)) return [];
  return fs.readdirSync(full, { withFileTypes: true }).flatMap((entry) => (entry.isDirectory() ? filesUnder(`${dir}/${entry.name}`) : [`${dir}/${entry.name}`]));
}

/** The line naming a copy's source, after its front matter — an agent reads a rule's or a skill's metadata from the top. */
function marked(text, source) {
  const front = /^---\n[\s\S]*?\n---\n/.exec(text)?.[0] ?? "";
  return `${front}<!-- ${MARK} ${source} — edit the source, never this copy. -->\n${text.slice(front.length)}`;
}

// A command's front matter (its `description:`) is Claude Code's; Cursor sends a command's text to the model as is.
const withoutFront = (text) => text.replace(/^---\n[\s\S]*?\n---\n/, "");

/** A command as Cursor lists it — by its first line: the description first, the line naming the source last. */
function cursorCommand(text, source, skills) {
  const front = /^---\n([\s\S]*?)\n---\n/.exec(text)?.[1] ?? "";
  const description = /^description:\s*"?(.*?)"?\s*$/m.exec(front)?.[1];
  const body = withoutFront(text).replace(/\{\{skill:([a-z0-9-]+)\}\}/g, `@${skills}/$1/SKILL.md`).replace(/\n*$/, "\n");
  return `${description ? `${description}.\n\n` : ""}${body}\n<!-- ${MARK} ${source} — edit the source, never this copy. -->\n`;
}

/** A Cursor rule's front matter as Claude Code reads it: `paths:` from its globs; none for an always-on rule. */
function claudeRule(text, source) {
  const front = /^---\n([\s\S]*?)\n---\n/.exec(text);
  const body = front ? text.slice(front[0].length) : text;
  const globs = front && !/^alwaysApply:\s*true\s*$/m.test(front[1]) ? (/^globs:\s*(.+)$/m.exec(front[1])?.[1] ?? "") : "";
  const paths = globs.split(",").map((glob) => glob.trim()).filter(Boolean);
  return marked(`${paths.length ? `---\npaths:\n${paths.map((glob) => `  - "${glob}"`).join("\n")}\n---\n` : ""}${body}`, source);
}

const json = (value) => `${JSON.stringify(value, null, 2)}\n`;

// A devDependency's MCP server runs through node in Claude Code: its npx needs a `cmd /c` wrapper on Windows.
const LOCAL_BINS = { "playwright-mcp": "node_modules/@playwright/mcp/cli.js" };

/** The MCP servers as .mcp.json — Claude Code's and Copilot's: a stdio server named so, run through node. */
function claudeMcp(text) {
  const config = JSON.parse(text);
  for (const [name, server] of Object.entries(config.mcpServers ?? {})) {
    const bin = server.command === "npx" && LOCAL_BINS[server.args?.[0]];
    config.mcpServers[name] = { type: "stdio", ...server, ...(bin ? { command: "node", args: [bin, ...server.args.slice(1)] } : {}) };
  }
  return json(config);
}

/** A rule's front matter read: its description, globs and whether it is always on — and its body. */
function ruleFront(text) {
  const front = /^---\n([\s\S]*?)\n---\n/.exec(text);
  const field = (key) => (front ? new RegExp(`^${key}:\\s*(.+)$`, "m").exec(front[1])?.[1]?.trim() : undefined);
  const globs = (field("globs") ?? "").split(",").map((glob) => glob.trim()).filter(Boolean);
  return { body: front ? text.slice(front[0].length) : text, description: field("description") ?? "", globs, always: field("alwaysApply") === "true" };
}

/** A rule by file as Copilot reads it: `applyTo` from its globs. */
function copilotInstruction(text, source) {
  const { body, description, globs } = ruleFront(text);
  return marked(`---\napplyTo: ${JSON.stringify(globs.join(", "))}\ndescription: ${JSON.stringify(description)}\n---\n${body}`, source);
}

/** Copilot's always-on instructions, one file: the Copilot note, then each always-on rule. */
function copilotInstructions() {
  const sources = [`${SOURCE}/notes/copilot.md`, ...filesUnder(`${SOURCE}/rules`).filter((file) => ruleFront(read(file)).always).sort()];
  const bodies = sources.filter((file) => fs.existsSync(path.join(ROOT, file))).map((file) => ruleFront(read(file)).body.trim());
  return { file: ".github/copilot-instructions.md", source: sources.join(", "), text: `<!-- ${MARK} ${sources.join(", ")} — edit the sources, never this copy. -->\n\n${bodies.join("\n\n---\n\n")}\n` };
}

/** The skills the kit has, by their folder's name in agents/skills/. */
const skillNames = () => (fs.existsSync(path.join(ROOT, SOURCE, "skills")) ? fs.readdirSync(path.join(ROOT, SOURCE, "skills")) : []);

/** A command no skill is named after, as a Copilot skill — Copilot calls skills by name, it reads no commands. */
function copilotCommandSkill(text, source, name) {
  const description = /^description:\s*"?(.*?)"?\s*$/m.exec(/^---\n([\s\S]*?)\n---\n/.exec(text)?.[1] ?? "")?.[1] ?? name;
  const body = withoutFront(text).replace(/\{\{skill:([a-z0-9-]+)\}\}/g, "the `$1` skill (`.github/skills/$1/SKILL.md`)");
  return marked(`---\nname: ${name}\ndescription: ${JSON.stringify(description)}\n---\n${body}`, source);
}

/** agents/hooks.json as Copilot's hook file: the stop hook on its agentStop event. */
function copilotHooks(text) {
  const { stop } = JSON.parse(text);
  return json({ version: 1, hooks: stop ? { agentStop: [{ type: "command", command: `${stop} --agent copilot`, timeoutSec: 120 }] } : {} });
}

/**
 * agents/hooks.json and agents/permissions.json as Claude Code's project settings: what the agent may do without
 * asking (the Playwright MCP, the kit's scripts, git that only reads), what it is never let to (reading cookies and
 * storage into the chat, 02-guardrails), and the stop hook on its Stop event.
 */
function claudeSettings(text) {
  const { stop } = JSON.parse(text);
  const permissions = fs.existsSync(path.join(ROOT, SOURCE, "permissions.json")) ? JSON.parse(read(`${SOURCE}/permissions.json`)) : undefined;
  return json({ ...(permissions ? { permissions } : {}), hooks: stop ? { Stop: [{ hooks: [{ type: "command", command: `${stop} --agent claude`, timeout: 120 }] }] } : {} });
}

/** agents/hooks.json as Cursor's hooks file. */
function cursorHooks(text) {
  const { stop } = JSON.parse(text);
  return json({ version: 1, hooks: stop ? { stop: [{ command: `${stop} --agent cursor` }] } : {} });
}

/**
 * The /review brief as a `reviewer` subagent (Claude Code's, Copilot's) — a fresh context is the new chat the
 * brief asks for.
 */
function reviewerAgent(text, source) {
  const head = [
    "---",
    "name: reviewer",
    // Quoted: a " #" would start a YAML comment.
    'description: "Independent review of tests this kit\'s agent wrote, against their manual cases — a fresh context that never saw how they were written. Use for the verify skill\'s full review (§6.2), given `<plan path> #<n> … — <spec paths>`."',
    "---",
    "",
    "You are the reviewer subagent: your context is fresh, so you are the new chat the brief below asks for. You are given",
    "`<plan path> #<n> … — <spec paths>`; answer with the report the brief describes.",
    "",
  ].join("\n");
  return marked(`${head}\n${withoutFront(text)}`, source);
}

const skillCopy = (source, text, skills) => [{ file: source.replace(/^agents\/skills\//, `${skills}/`), text: source.endsWith(".md") ? marked(text, source) : text }];
// Cursor reads Claude Code's skill folder: with Claude Code chosen, a copy of its own would show each skill twice.
const cursorSkills = (chosen) => (chosen.includes("claude") ? ".claude/skills" : ".cursor/skills");

/**
 * Each agent: its id, the folders its copies live in, its config files, its copies of one source file — [{ file,
 * text }], none for a source it has no place for, given the agents chosen — and the copies it makes of several
 * sources at once (`aggregate`).
 */
const TARGETS = [
  {
    id: "cursor",
    folders: [".cursor/rules", ".cursor/skills", ".cursor/commands"],
    files: [".cursor/mcp.json", ".cursor/hooks.json"],
    copies(source, text, chosen) {
      const skills = cursorSkills(chosen);
      const rule = /^agents\/rules\/(.+)\.md$/.exec(source);
      if (rule) return [{ file: `.cursor/rules/${rule[1]}.mdc`, text: marked(text, source) }];
      if (source.startsWith("agents/skills/")) return skills === ".cursor/skills" ? skillCopy(source, text, skills) : [];
      if (source.startsWith("agents/commands/")) return [{ file: source.replace(/^agents\//, ".cursor/"), text: cursorCommand(text, source, skills) }];
      if (source === "agents/mcp.json") return [{ file: ".cursor/mcp.json", text }];
      if (source === "agents/hooks.json") return [{ file: ".cursor/hooks.json", text: cursorHooks(text) }];
      return [];
    },
  },
  {
    id: "claude",
    folders: [".claude/rules", ".claude/skills", ".claude/commands", ".claude/agents"],
    files: [".mcp.json", ".claude/settings.json"],
    copies(source, text) {
      const rule = /^agents\/rules\/(.+)\.md$/.exec(source);
      if (rule) return [{ file: `.claude/rules/${rule[1]}.md`, text: claudeRule(text, source) }];
      if (source === "agents/notes/claude-code.md") return [{ file: ".claude/rules/claude-code.md", text: marked(text, source) }];
      if (source.startsWith("agents/skills/")) return skillCopy(source, text, ".claude/skills");
      if (source === "agents/commands/review.md") return [{ file: ".claude/agents/reviewer.md", text: reviewerAgent(text, source) }];
      if (source.startsWith("agents/commands/")) {
        return [{ file: source.replace(/^agents\//, ".claude/"), text: marked(text.replace(/\{\{skill:([a-z0-9-]+)\}\}/g, "the `$1` skill (`.claude/skills/$1/SKILL.md`)"), source) }];
      }
      if (source === "agents/mcp.json") return [{ file: ".mcp.json", text: claudeMcp(text) }];
      if (source === "agents/hooks.json") return [{ file: ".claude/settings.json", text: claudeSettings(text) }];
      return [];
    },
  },
  {
    id: "copilot",
    folders: [".github/instructions", ".github/skills", ".github/agents"],
    files: [".github/copilot-instructions.md", ".github/hooks/playwright-ai-kit.json", ".mcp.json"],
    copies(source, text, chosen) {
      const rule = /^agents\/rules\/(.+)\.md$/.exec(source);
      if (rule) return ruleFront(text).always ? [] : [{ file: `.github/instructions/${rule[1]}.instructions.md`, text: copilotInstruction(text, source) }];
      if (source.startsWith("agents/skills/")) return skillCopy(source, text, ".github/skills");
      const command = /^agents\/commands\/(.+)\.md$/.exec(source)?.[1];
      if (command === "review") return [{ file: ".github/agents/reviewer.agent.md", text: reviewerAgent(text, source) }];
      if (command && !skillNames().includes(command)) return [{ file: `.github/skills/${command}/SKILL.md`, text: copilotCommandSkill(text, source, command) }];
      if (source === "agents/mcp.json") return chosen.includes("claude") ? [] : [{ file: ".mcp.json", text: claudeMcp(text) }];
      if (source === "agents/hooks.json") return [{ file: ".github/hooks/playwright-ai-kit.json", text: copilotHooks(text) }];
      return [];
    },
    aggregate: () => [copilotInstructions()],
  },
];

/** The copies of these agents, given the agents chosen: [{ file, text, source, agent }]. */
function copiesOf(targets, chosen) {
  const single = filesUnder(SOURCE).flatMap((source) => {
    const text = read(source);
    return targets.flatMap((target) => target.copies(source, text, chosen).map((copy) => ({ ...copy, source, agent: target.id })));
  });
  return [...single, ...targets.flatMap((target) => (target.aggregate?.() ?? []).map((copy) => ({ ...copy, agent: target.id })))];
}

/**
 * The copies that do not match agents/ and the choice: [{ file, problem, source?, text? }] — problem "missing",
 * "differs" (edited by hand, or its source edited since) or "stale" (a copy whose source is gone or whose agent
 * is not chosen: one carrying the source line, or an agent's config file exactly as written here).
 */
export function drift() {
  const chosen = chosenAgents();
  const planned = copiesOf(TARGETS.filter(({ id }) => chosen.includes(id)), chosen);
  const wanted = new Set(planned.map(({ file }) => file));
  const found = [];
  for (const copy of planned) {
    if (!fs.existsSync(path.join(ROOT, copy.file))) found.push({ ...copy, problem: "missing" });
    else if (read(copy.file) !== copy.text) found.push({ ...copy, problem: "differs" });
  }
  for (const file of TARGETS.flatMap(({ folders }) => folders).flatMap(filesUnder)) {
    if (!wanted.has(file) && read(file).includes(MARK)) found.push({ file, problem: "stale" });
  }
  // An agent no longer chosen: its config files exactly as written here go — but a file a chosen agent writes too (.mcp.json).
  const unchosen = TARGETS.filter(({ id }) => !chosen.includes(id));
  for (const copy of copiesOf(unchosen, chosen)) {
    const own = unchosen.some(({ files }) => files.includes(copy.file));
    if (own && !wanted.has(copy.file) && fs.existsSync(path.join(ROOT, copy.file)) && read(copy.file) === copy.text) found.push({ file: copy.file, problem: "stale" });
  }
  return [...new Map(found.map((item) => [item.file, item])).values()];
}

/** A folder left empty by a removal goes too, up to the agent's own folder (.cursor, .claude). */
function pruneEmpty(dir) {
  const full = path.join(ROOT, dir);
  if (!fs.existsSync(full) || !fs.statSync(full).isDirectory()) return;
  for (const entry of fs.readdirSync(full)) pruneEmpty(`${dir}/${entry}`);
  if (fs.readdirSync(full).length === 0) fs.rmdirSync(full);
}

/** Writes the chosen agents' copies and removes the stale ones — what was done, as drift() lists it. */
export function sync() {
  const found = drift();
  for (const { file, problem, text } of found) {
    const full = path.join(ROOT, file);
    if (problem === "stale") fs.rmSync(full);
    else {
      fs.mkdirSync(path.dirname(full), { recursive: true });
      fs.writeFileSync(full, text);
    }
  }
  for (const dir of [".cursor", ".claude", ".github/instructions", ".github/skills", ".github/agents", ".github/hooks", ".github"]) pruneEmpty(dir);
  return found;
}

function main(argv) {
  const agents = chosenAgents().map((id) => AGENTS[id]).join(", ");
  if (argv.includes("--check")) {
    const found = drift();
    for (const { file, problem, source } of found) console.log(`${file} — ${problem}${source ? ` (source ${source})` : ""}`);
    console.log(found.length ? `\n${found.length} copy(ies) out of date — npm run agents:sync` : `Every copy matches agents/ (${agents}).`);
    process.exit(found.length ? 1 : 0);
  }
  const found = sync();
  console.log(found.length ? `${found.length} copy(ies) written or removed (${agents}).` : `Every copy already matches agents/ (${agents}).`);
}

